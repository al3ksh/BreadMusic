import { chromium, expect } from '@playwright/test';
import fs from 'node:fs/promises';
const browser = await chromium.launch();
await fs.mkdir('.tmp/landing-preview',{recursive:true});
try {
  for (const [name,width,height] of [['desktop',1536,832],['mobile',390,844]]) {
    const page = await browser.newPage({viewport:{width,height},reducedMotion:'reduce'});
    const errors=[]; page.on('pageerror',error=>errors.push(error.message));
    await page.addInitScript(()=>localStorage.setItem('bread_cookie_notice_v1','accepted'));
    await page.route('**/demo/api/search',route=>route.fulfill({json:{tracks:[{title:'TACONAFIDE - Tamagotchi',artist:'Taco Hemingway',duration:'3:25',cover:'instant-crush',uri:'https://youtu.be/example',seekable:true}],playlist:null}}));
    await page.route('**/demo/api/lyrics',route=>route.fulfill({json:{lyrics:{plainLyrics:'Original test line one.\nOriginal test line two.',lines:[{time:0,text:'Original test line one.'},{time:20000,text:'Original test line two.'}],instrumental:false,provider:'Fixture'}}}));
    await page.goto('http://localhost:3181/preview/landing',{waitUntil:'networkidle'});
    const input=page.getByRole('combobox');
    await input.fill('/pl'); await expect(page.getByRole('listbox',{name:'Bread commands'})).toBeVisible();
    await input.press('Enter'); await expect(input).toHaveValue('');
    await expect(page.locator('[class*="commandToken"]')).toContainText('/play');
    await input.fill('taconafide');
    await expect(page.getByRole('listbox',{name:'Matching tracks'}).getByRole('option')).toHaveCount(1);
    await page.locator('#playground').screenshot({path:`.tmp/landing-preview/${name}-discord-autocomplete.png`});
    const count=await page.getByRole('log').locator('article').count();
    await input.press('Enter'); await expect(page.getByRole('log').locator('article')).toHaveCount(count);
    await expect(input).toHaveValue('Taco Hemingway - TACONAFIDE - Tamagotchi');
    await input.press('Enter'); await expect(page.getByRole('log').locator('article').last()).toContainText('Tamagotchi');
    await page.getByRole('button',{name:'Open Activity preview'}).click();
    const frame=page.frameLocator('iframe[title="Bread Activity preview"]');
    const activity=frame.getByTestId('activity-demo');
    await expect(activity).toBeVisible();
    await expect(activity.locator('.activity-primary-controls button')).toHaveCount(4);
    await expect(activity.locator('.activity-secondary-controls button')).toHaveCount(4);
    await expect(activity.getByRole('button',{name:'Autoplay off'})).toBeDisabled();
    expect(await activity.evaluate(el=>getComputedStyle(el).fontFamily)).not.toContain('Manrope');
    expect(await activity.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(await activity.evaluate(()=>innerWidth));
    await page.locator('iframe').screenshot({path:`.tmp/landing-preview/${name}-native-activity.png`});
    await activity.getByRole('button',{name:'Pause',exact:true}).click();
    const seek=activity.getByRole('slider',{name:'Track position',exact:true});
    await seek.focus(); await seek.press('Home'); await seek.press('PageUp');
    await activity.getByRole('button',{name:'Add music',exact:true}).click();
    await expect(activity.locator('#activity-upload')).toBeDisabled();
    await expect(activity.locator('.activity-upload-picker')).toBeVisible();
    await activity.locator('aside').getByRole('button',{name:'Close panel',exact:true}).click();
    await expect(activity.locator('aside')).not.toBeVisible();
    await activity.getByRole('button',{name:'Lyrics',exact:true}).click();
    await expect(activity.locator('.activity-lyrics-plain')).toContainText('Original test line');
    await activity.getByRole('button',{name:'Live sync',exact:true}).click();
    await expect(activity.locator('.activity-lyrics-list .active')).toHaveText('Original test line two.');
    await page.locator('iframe').screenshot({path:`.tmp/landing-preview/${name}-native-lyrics.png`});
    await activity.getByRole('button',{name:'Karaoke',exact:true}).click();
    await expect(activity.locator('aside')).not.toBeVisible();
    await expect(activity.locator('.activity-karaoke-lines .is-current')).toHaveText('Original test line two.');
    await page.locator('iframe').screenshot({path:`.tmp/landing-preview/${name}-native-karaoke.png`});
    await activity.getByRole('button',{name:'Exit karaoke'}).click();
    await expect(activity.locator('.activity-player-stage')).toBeVisible();
    await activity.getByRole('button',{name:/^Queue/}).click();
    await activity.getByRole('tab',{name:'History',exact:true}).click();
    await expect(activity.locator('.activity-empty')).toContainText('No listening history yet');
    await activity.locator('aside').getByRole('button',{name:'Close panel',exact:true}).click();
    await expect(activity.locator('aside')).not.toBeVisible();
    await activity.getByRole('button',{name:'Skip',exact:true}).click();
    await activity.getByRole('button',{name:/^Queue/}).click();
    await expect(activity.locator('.activity-history-row')).toHaveCount(1);
    expect(errors).toEqual([]);
    console.log(`${name}: native Activity styles, eight controls, disabled autoplay/upload, Discord autocomplete, live lyrics, karaoke and history passed`);
    await page.close();
  }
} finally {await browser.close();}
