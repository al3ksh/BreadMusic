import { chromium, expect } from '@playwright/test';
const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport:{width:1366,height:768} });
  page.setDefaultTimeout(15000);
  await page.addInitScript(() => localStorage.setItem('bread_cookie_notice_v1','accepted'));
  await page.route('**/demo/api/search', route => route.fulfill({ json: { tracks:Array.from({length:42},(_,i)=>({title:`Playlist track ${i+1}`,artist:'Preview artist',duration:'4:00',cover:'instant-crush',uri:`https://youtu.be/sample${i}`,seekable:true})),playlist:{name:'Test playlist',total:42,truncated:false} } }));
  await page.goto('http://localhost:3181/preview/landing');
  const input = page.getByRole('combobox');
  await input.fill('/play playlist'); await input.press('Escape'); await input.press('Enter');
  await expect(page.getByRole('log')).toHaveAttribute('aria-busy','false');
  await page.getByRole('button',{name:'Open Activity preview'}).click();
  const activity = page.frameLocator('iframe[title="Bread Activity preview"]').getByTestId('activity-demo');
  await activity.getByRole('button',{name:'Pause',exact:true}).click();
  const seek = activity.getByRole('slider',{name:'Track position',exact:true});
  await seek.focus(); await seek.press('Home'); await seek.press('PageUp');
  const position = await seek.inputValue();
  await page.waitForTimeout(1100); await expect(seek).toHaveValue(position);
  await activity.getByRole('button',{name:'Volume 100%'}).click();
  const volume = activity.getByRole('slider',{name:'Volume',exact:true});
  await volume.focus(); await volume.press('Home'); await volume.press('ArrowRight');
  await expect(activity.getByRole('button',{name:'Volume 1%'})).toBeVisible();
  await activity.getByRole('button',{name:/^Queue/}).click();
  await expect(activity.locator('.activity-queue-row')).toHaveCount(20);
  await activity.getByRole('button',{name:'Load more (20/44)'}).click();
  await expect(activity.locator('.activity-queue-row')).toHaveCount(40);
  await activity.getByRole('button',{name:'Load more (40/44)'}).click();
  await expect(activity.locator('.activity-queue-row')).toHaveCount(44);
  const last = activity.locator('.activity-queue-row').last();
  await last.scrollIntoViewIfNeeded();
  const area = activity.locator('.activity-drawer-body');
  const box = await area.evaluate(el=>{const r=el.getBoundingClientRect();return {x:r.x,y:r.y}});
  const before = await area.evaluate(el=>el.scrollTop);
  await last.dispatchEvent('dragstart');
  await area.dispatchEvent('dragover',{clientY:box.y+10,clientX:box.x+20});
  await page.waitForTimeout(500);
  expect(await area.evaluate(el=>el.scrollTop)).toBeLessThan(before);
  const first = activity.locator('.activity-queue-row').first();
  await first.dispatchEvent('drop'); await first.dispatchEvent('dragend');
  await expect(first).toContainText('Playlist track 42');
  await activity.locator('aside').getByRole('button',{name:'Close panel',exact:true}).click();
  await expect(activity.locator('aside')).not.toBeVisible();
  await activity.getByRole('button',{name:'Skip',exact:true}).click();
  await expect(activity.locator('.activity-track-copy h1')).toHaveText('Playlist track 42');
  await activity.getByRole('button',{name:/^Queue/}).click();
  await expect(activity.locator('.activity-queue-row')).toHaveCount(43);
  await activity.locator('aside').getByRole('button',{name:'Close panel',exact:true}).click();
  await page.getByRole('tab',{name:'Slash commands',exact:true}).click();
  await expect(page.locator('[data-live-player]')).toContainText('Playlist track 42');
  await expect(page.locator('[data-live-player]')).toContainText('1%');
  const separate = await browser.newPage(); await separate.goto('http://localhost:3181/preview/landing');
  await expect(separate.locator('[data-live-player]')).toContainText('Instant Crush'); await separate.close();

  const gallery = page.getByRole('region',{name:'Bread Arcade gallery'});
  await gallery.scrollIntoViewIfNeeded(); await page.mouse.move(0,0); await page.locator('h1').evaluate(el=>{document.activeElement?.blur();});
  await expect(gallery.locator('img[data-active=true]')).toHaveAttribute('alt',/RPS/);
  await expect(gallery.locator('img[data-active=true]')).toHaveAttribute('alt',/Blackjack/,{timeout:8000});
  await gallery.hover(); await page.waitForTimeout(6300);
  await expect(gallery.locator('img[data-active=true]')).toHaveAttribute('alt',/Blackjack/);
  await gallery.getByRole('button',{name:'Slots',exact:true}).click(); await page.mouse.move(0,0); await page.evaluate(()=>document.activeElement?.blur());
  await page.waitForTimeout(6300); await expect(gallery.locator('img[data-active=true]')).toHaveAttribute('alt',/Slots/);
  await gallery.getByRole('button',{name:'Resume slideshow'}).click(); await page.mouse.move(0,0); await page.evaluate(()=>document.activeElement?.blur());
  await expect(gallery.locator('img[data-active=true]')).toHaveAttribute('alt',/Roulette/,{timeout:8000});
  await page.locator('h1').scrollIntoViewIfNeeded(); await page.waitForTimeout(6300);
  await expect(gallery.locator('img[data-active=true]')).toHaveAttribute('alt',/Roulette/);
  await page.emulateMedia({reducedMotion:'reduce'}); await gallery.scrollIntoViewIfNeeded(); await page.waitForTimeout(6300);
  await expect(gallery.locator('img[data-active=true]')).toHaveAttribute('alt',/Roulette/);
  console.log('Keyboard seek/volume, pause clock, 44-track pagination/reorder/autoscroll, retained pages, tab isolation and carousel pause/reduced motion passed.');
} finally { await browser.close(); }
